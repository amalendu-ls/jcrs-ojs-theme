"""Build the JCRS website drafts.

  src/pages/*.html  page content (one file per page, with a header comment)
  src/shell.html    preview header / menu / sidebar / footer
  src/*.css         styles

Outputs
  site/  full preview pages that link to each other (open site/index.html)
  ojs/   paste-ready blocks for OJS with the real journal URLs

Run:  python build.py
"""
import json
import re
import shutil
from pathlib import Path

from toc import archive_html, archive_summary, home_toc, toc_sections

ROOT = Path(__file__).resolve().parent
SRC, SITE, OJS = ROOT / "src", ROOT / "site", ROOT / "ojs"
BASE = "https://culturalstudies.in/journal/index.php/JCRS"

PAGES = {  # source file -> preview file name
    "home": "index.html",
    "about": "about.html",
    "editorial-team": "editorial-team.html",
    "current-issue": "current-issue.html",
    "archives": "archives.html",
    "author-guidelines": "author-guidelines.html",
    "contact": "contact.html",
}
# Pages whose content is pasted into an OJS field (the rest are generated by OJS and only styled).
PASTEABLE = ["home", "about", "editorial-team", "author-guidelines", "contact"]

PREVIEW_LINKS = {
    "home": "index.html", "about": "about.html", "editorial": "editorial-team.html",
    "current": "current-issue.html", "archive": "archives.html", "guidelines": "author-guidelines.html",
    "contact": "contact.html", "submit": "author-guidelines.html",
}
OJS_LINKS = {
    "home": BASE, "about": f"{BASE}/about", "editorial": f"{BASE}/about/editorialTeam",
    "current": f"{BASE}/issue/current", "archive": f"{BASE}/issue/archive",
    "guidelines": f"{BASE}/about/submissions", "contact": f"{BASE}/about/contact",
    "submit": f"{BASE}/submission/wizard",
}
CURRENT_ISSUE_ID = "9"
FOOTER_NOTE = """<!-- Page footer. Paste at: Settings > Website > Appearance > Setup > "Page footer" (Source code < > button). -->
"""
EIC_BLOCK_NOTE = """<!-- Sidebar block. Website > Plugins > enable "Custom Block Manager" > Settings > Add Block (name: editor-in-chief),
     paste this (Source code < > button), then Website > Appearance > Setup > Sidebar: place it directly below "Make a Submission". -->
"""


def fill(text, links, preview):
    def repl(m):
        key = m.group(1)
        if key in links:
            return links[key]
        kind, *ids = key.split(":")
        if kind == "article":
            return f"{BASE}/article/view/{ids[0]}"
        if kind == "galley":
            return f"{BASE}/article/view/{ids[0]}/{ids[1]}"
        if kind == "img":
            return f"img/{ids[0]}" if preview else f"https://culturalstudies.in/journal/public/site/images/admin/{ids[0]}"
        if kind == "issue":
            if preview and ids[0] == CURRENT_ISSUE_ID:
                return links["current"]
            return f"{BASE}/issue/view/{ids[0]}"
        raise KeyError(f"Unknown link placeholder: {{{{{key}}}}}")
    return re.sub(r"\{\{([a-z]+(?::[\w.-]+)*)\}\}", repl, text)


def split_page(raw):
    m = re.match(r"\s*<!--(.*?)-->\s*", raw, re.S)
    meta = dict(re.findall(r"^\s*(\w+):\s*(.+)$", m.group(1), re.M))
    return meta, m.group(0).strip(), raw[m.end():]


def main():
    for d in (SITE, OJS):
        if d.exists():
            shutil.rmtree(d)
        d.mkdir()
    eic_block = (SRC / "blocks" / "editor-in-chief.html").read_text(encoding="utf-8")
    shell = (SRC / "shell.html").read_text(encoding="utf-8").replace("{{EIC_BLOCK}}", eic_block)
    footer = (SRC / "blocks" / "footer.html").read_text(encoding="utf-8")
    shell = shell.replace("{{FOOTER}}", footer)
    (OJS / "footer.html").write_text(FOOTER_NOTE + fill(footer, OJS_LINKS, False), encoding="utf-8")
    (OJS / "sidebar-block-editor-in-chief.html").write_text(
        EIC_BLOCK_NOTE + fill(eic_block, OJS_LINKS, False), encoding="utf-8")
    current_raw = split_page((SRC / "pages" / "current-issue.html").read_text(encoding="utf-8"))[2]
    data = json.loads((SRC / "data" / "current-issue.json").read_text(encoding="utf-8"))
    archive = json.loads((SRC / "data" / "archive.json").read_text(encoding="utf-8"))

    for name, out in PAGES.items():
        raw = (SRC / "pages" / f"{name}.html").read_text(encoding="utf-8")
        meta, comment, body = split_page(raw)
        content = body.replace("{{TOC}}", home_toc(data)).replace("{{TOC_SECTIONS}}", toc_sections(data))
        content = content.replace("{{ARCHIVE_SUMMARY}}", archive_summary(archive)).replace("{{ARCHIVE}}", archive_html(archive))
        page = shell.replace("{{CONTENT}}", content).replace("{{TITLE}}", meta["title"]).replace("{{NAV}}", meta["nav"])
        (SITE / out).write_text(fill(page, PREVIEW_LINKS, True), encoding="utf-8")
        if name in PASTEABLE:
            paste = re.sub(r"\n\s*\{\{TOC\}\}\n", "\n", body)  # OJS lists the issue itself
            (OJS / f"{name}.html").write_text(fill(comment + "\n" + paste, OJS_LINKS, False), encoding="utf-8")

    desc = re.search(r"<!-- ISSUE DESCRIPTION START -->\n(.*?)<!-- ISSUE DESCRIPTION END -->", current_raw, re.S).group(1)
    (OJS / "issue-description-vol5-no1.html").write_text(
        "<!-- Paste at: Issues > Back Issues > Vol. 5 No. 1 > Issue Data > Description (Source code < > button).\n"
        "     Replaces the old text that says \"January, 2026\". -->\n" + desc, encoding="utf-8")

    for css in ("jcrs-custom.css", "preview.css"):
        shutil.copy(SRC / css, SITE / css)
    shutil.copy(SRC / "jcrs-custom.css", OJS / "jcrs-custom.css")
    for d in (SITE, OJS):
        shutil.copytree(SRC / "img", d / "img")
    print("Built", len(PAGES), "preview pages in site/ and", len(PASTEABLE) + 2, "files in ojs/")


if __name__ == "__main__":
    main()
